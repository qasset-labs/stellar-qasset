#!/usr/bin/env python3
"""Disposable Testnet SAC authority demonstration. Public records never contain secrets.

ML-DSA-65 uses the unaudited RustCrypto ml-dsa 0.1.1 verifier inside contract
Wasm, not a CAP-87 host function. Issuer locking requires the exact environment
gate and an issuer generated by this invocation. Existing issuers are never inputs.
"""
import argparse
import copy
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import urllib.error
import urllib.request

from stellar_sdk import (Account, Address, Asset, Keypair, SorobanServer,
                         TransactionBuilder, scval, xdr)
from stellar_sdk.auth import authorization_payload_hash, authorize_entry
from stellar_sdk.operation import AuthorizationFlag, TrustLineFlags
from stellar_sdk.soroban_rpc import SimulateTransactionResponse

ROOT = Path(__file__).resolve().parents[1]
RPC = "https://soroban-testnet.stellar.org"
HORIZON = "https://horizon-testnet.stellar.org"
PASSPHRASE = "Test SDF Network ; September 2015"
REGISTRY_HASH = "26f684edb7e3255ac1617f1455fbfcf886a0f5b189f31974b873a5bc0f98a207"


def now():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def request(url, payload=None):
    data = None if payload is None else json.dumps(payload).encode()
    req = urllib.request.Request(url, data=data, headers={
        "Content-Type": "application/json", "User-Agent": "stellar-cli/26.0.0"})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=25) as response:
                return json.load(response)
        except (TimeoutError, urllib.error.URLError) as error:
            if isinstance(error, urllib.error.HTTPError) and error.code not in (429, 500, 502, 503, 504):
                raise
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def rpc(method, params=None):
    result = request(RPC, {"jsonrpc": "2.0", "id": 1, "method": method, "params": params or {}})
    if "error" in result:
        raise RuntimeError(f"RPC {method}: {result['error']}")
    return result["result"]


def native(value):
    value = scval.to_native(value)
    def convert(v):
        if isinstance(v, Address):
            return v.address
        if isinstance(v, bytes):
            return {"bytes_hex": v.hex()}
        if isinstance(v, dict):
            return {str(k): convert(w) for k, w in v.items()}
        if isinstance(v, list):
            return [convert(w) for w in v]
        return v
    return convert(value)


def build_read(source, contract, function, args=()):
    return (TransactionBuilder(Account(source, 0), PASSPHRASE, base_fee=100)
            .append_invoke_contract_function_op(contract, function, list(args))
            .set_timeout(300).build())


def issuer_lock_allowed(environment, issuer, created_issuers, state):
    """Fail closed before constructing a lock operation; absence of the gate is pending."""
    if environment.get("QASSET_ALLOW_DISPOSABLE_ISSUER_LOCK") != "YES":
        return False
    if (issuer not in created_issuers or state.get("account_id") != issuer
            or not state.get("signers")
            or any(s["key"] != issuer for s in state["signers"])
            or not any(s["weight"] > 0 for s in state["signers"])):
        raise RuntimeError("lock requires this run's fresh issuer with only its active master signer")
    return True


def prepare_and_sign(tx, simulation, key):
    prepared = SorobanServer(RPC).prepare_transaction(tx, SimulateTransactionResponse.model_validate(simulation))
    # CAP-66 permits a resource fee beyond uint32 only inside a fee-bump envelope.
    # Keep the full resource declaration; the signed outer int64 fee covers it.
    if prepared.transaction.fee > 0xffffffff:
        prepared.transaction.fee = 100
        prepared.sign(key)
        prepared = TransactionBuilder.build_fee_bump_transaction(key.public_key, 100, prepared, PASSPHRASE)
    prepared.sign(key)
    return prepared


def read(source, contract, function, args=()):
    tx = build_read(source, contract, function, args)
    result = rpc("simulateTransaction", {"transaction": tx.to_xdr(), "authMode": "enforce"})
    if result.get("error"):
        raise RuntimeError(f"Read {function}: {result['error']}")
    return {"contract": contract, "function": function, "args_xdr": [a.to_xdr() for a in args],
            "request_xdr": tx.to_xdr(), "result": result,
            "value": native(xdr.SCVal.from_xdr(result["results"][0]["xdr"]))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wasm-dir", type=Path, default=ROOT / "target/wasm32v1-none/release")
    parser.add_argument("--signer", type=Path, default=ROOT / "tools/qasset-sac-signer/target/release/qasset-sac-signer")
    parser.add_argument("--output", type=Path, default=ROOT / "deployments/testnet/qasset-poc.json")
    parser.add_argument("--network-passphrase", default=PASSPHRASE)
    args = parser.parse_args()
    if args.network_passphrase != PASSPHRASE:
        parser.error("only Stellar Testnet is permitted")
    if args.output.exists():
        parser.error("output already exists; preserve the previous run and choose a new output")
    journal = {"schema": "qasset-poc-deployment-v1", "status": "in_progress", "recorded_at_utc": now(),
               "network": "testnet", "network_passphrase": PASSPHRASE, "rpc_url": RPC,
               "horizon_url": HORIZON, "assets": {}, "observations": [], "artifacts": {},
               "lock_gate": {"environment_enabled": os.environ.get("QASSET_ALLOW_DISPOSABLE_ISSUER_LOCK") == "YES",
                             "state": "PENDING", "issuer_created_this_run": False},
               "verification": "ML-DSA-65 inside Wasm; RustCrypto ml-dsa 0.1.1, unaudited; no CAP-87 host call"}

    def save():
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary = args.output.with_suffix(".tmp")
        temporary.write_text(json.dumps(journal, indent=2) + "\n")
        temporary.replace(args.output)

    def record(item):
        item["id"] = f"observation-{len(journal['observations']) + 1:03d}"
        journal["observations"].append(item)
        save()
        return item

    def account(public):
        return request(f"{HORIZON}/accounts/{public}")

    def builder(key):
        state = account(key.public_key)
        return TransactionBuilder(Account(key.public_key, int(state["sequence"])), PASSPHRASE, base_fee=100)

    def simulate(tx, mode="enforce"):
        return rpc("simulateTransaction", {"transaction": tx.to_xdr(), "authMode": mode})

    def submit(tx, key, label, asset=None, soroban=False, expected="SUCCESS"):
        if soroban:
            operation = tx.transaction.operations[0]
            if not operation.auth:
                recording = simulate(tx, "record")
                if recording.get("error"):
                    raise RuntimeError(f"{label}: source authorization recording failed: {recording['error']}")
                auths = [xdr.SorobanAuthorizationEntry.from_xdr(a)
                         for a in recording["results"][0].get("auth", [])]
                if any(a.credentials.type != xdr.SorobanCredentialsType.SOROBAN_CREDENTIALS_SOURCE_ACCOUNT for a in auths):
                    raise RuntimeError("refusing to auto-authorize any identity other than the transaction source")
                operation.auth = auths
            sim = simulate(tx)
            if sim.get("error"):
                raise RuntimeError(f"{label}: enforced simulation rejected: {sim['error']}")
            tx = prepare_and_sign(tx, sim, key)
        else:
            tx.sign(key)
        tx_hash = tx.hash_hex()
        response = rpc("sendTransaction", {"transaction": tx.to_xdr()})
        if response["status"] not in ("PENDING", "DUPLICATE"):
            # A send rejection is not a failed on-chain transaction.
            record({"label": label, "asset": asset, "kind": "submission_rejection", "expected": expected,
                    "observed": "REJECT", "hash": tx_hash, "envelope_xdr": tx.to_xdr(), "response": response})
            if expected == "REJECT" and response.get("errorResultXdr"):
                result = xdr.TransactionResult.from_xdr(response["errorResultXdr"])
                if result.result.code == xdr.TransactionResultCode.txBAD_AUTH:
                    return None
            raise RuntimeError(f"{label}: submission rejected before inclusion: {response}")
        for _ in range(50):
            receipt = rpc("getTransaction", {"hash": tx_hash})
            if receipt["status"] != "NOT_FOUND":
                break
            time.sleep(1)
        observed = receipt["status"]
        record({"label": label, "asset": asset, "kind": "transaction", "expected": expected,
                "observed": observed, "hash": tx_hash, "envelope_xdr": tx.to_xdr(),
                "receipt": receipt, "simulation": sim if soroban else None})
        if observed != ("SUCCESS" if expected == "SUCCESS" else "FAILED"):
            raise RuntimeError(f"{label}: expected {expected}, observed {observed}")
        print(f"{label}: {observed} {tx_hash}", flush=True)
        return receipt

    def invoke(key, contract, function, values, label, asset=None):
        tx = (builder(key).append_invoke_contract_function_op(contract, function, values).set_timeout(300).build())
        return submit(tx, key, label, asset, soroban=True)

    def helper(*parts):
        completed = subprocess.run([str(args.signer.resolve()), *parts], cwd=ROOT, text=True,
                                   capture_output=True, timeout=45, check=False)
        if completed.returncode:
            raise RuntimeError(f"signer failed: {completed.stderr.strip()}")
        return bytes.fromhex(completed.stdout.strip())

    try:
        network = rpc("getNetwork")
        if network["passphrase"] != PASSPHRASE:
            raise RuntimeError("refusing network other than Testnet")
        journal["network_info"] = network
        journal["start_ledger"] = rpc("getLatestLedger")["sequence"]
        for name in ("qasset_sac_admin", "qasset_registry"):
            path = args.wasm_dir / (name + ".wasm")
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            if path.stat().st_size > 131072:
                raise RuntimeError("Wasm exceeds documented code limit")
            if name == "qasset_registry" and digest != REGISTRY_HASH:
                raise RuntimeError("registry build differs from the unchanged baseline")
            journal["artifacts"][str(path.resolve().relative_to(ROOT))] = {"sha256": digest, "bytes": path.stat().st_size}
        # Private directory and exclusive seed creation. No existing operator or issuer input.
        private = Path(tempfile.mkdtemp(prefix="qasset-poc-"))
        if private.resolve().is_relative_to(ROOT):
            raise RuntimeError("temporary key storage must be outside the repository")
        key_path = private / "sac-operator.seed"
        public = helper("keygen", "--out", str(key_path))
        if len(public) != 1952:
            raise RuntimeError("unexpected ML-DSA-65 public key length")
        journal["operator_public_key_hex"] = public.hex()
        journal["operator_public_key_sha256"] = hashlib.sha256(public).hexdigest()
        keys = {name: Keypair.random() for name in ("deployer", "issuer_QEXP", "issuer_QCTL", "holder_QEXP", "holder_QCTL")}
        generated = {key.public_key for key in keys.values()}
        journal["accounts"] = {name: key.public_key for name, key in keys.items()}
        # Keep recovery material only in private local storage, never in the public journal.
        fd = os.open(private / "accounts.json", os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        with os.fdopen(fd, "w") as stream:
            json.dump({name: key.secret for name, key in keys.items()}, stream)
        print(f"Private disposable run keys: {private} (outside repository)", flush=True)
        save()
        for name, key in keys.items():
            request("https://friendbot.stellar.org/?addr=" + key.public_key)
            print(f"Funded fresh {name}: {key.public_key}", flush=True)
        deployer = keys["deployer"]
        source = deployer.public_key
        for name in ("qasset_sac_admin", "qasset_registry"):
            tx = builder(deployer).append_upload_contract_wasm_op((args.wasm_dir / (name + ".wasm")).read_bytes()).set_timeout(300).build()
            submit(tx, deployer, "upload_" + name, soroban=True)

        def deploy(name, constructor, label, asset=None):
            digest = journal["artifacts"][str((args.wasm_dir / (name + ".wasm")).resolve().relative_to(ROOT))]["sha256"]
            tx = (builder(deployer).append_create_contract_op(digest, source, constructor_args=constructor,
                                                              salt=os.urandom(32)).set_timeout(300).build())
            receipt = submit(tx, deployer, label, asset, soroban=True)
            meta = xdr.TransactionMeta.from_xdr(receipt["resultMetaXdr"])
            soroban = meta.v4.soroban_meta if meta.v4 is not None else meta.v3.soroban_meta
            return scval.from_address(soroban.return_value).address

        registry = deploy("qasset_registry", [Address(source).to_xdr_sc_val()], "deploy_registry")
        journal["registry"] = {"id": registry, "admin": source, "wasm_sha256": REGISTRY_HASH, "revision_checked_writes": True}
        for code in ("QEXP", "QCTL"):
            issuer = keys["issuer_" + code]
            holder = keys["holder_" + code]
            asset = Asset(code, issuer.public_key)
            sac = asset.contract_id(PASSPHRASE)
            tx = (builder(issuer).append_set_options_op(set_flags=AuthorizationFlag.AUTHORIZATION_REQUIRED | AuthorizationFlag.AUTHORIZATION_REVOCABLE,
                    low_threshold=1, med_threshold=1, high_threshold=1).set_timeout(300).build())
            submit(tx, issuer, "issuer_flags", code)
            tx = builder(deployer).append_create_stellar_asset_contract_from_asset_op(asset).set_timeout(300).build()
            submit(tx, deployer, "deploy_sac", code, soroban=True)
            admin = deploy("qasset_sac_admin", [Address(sac).to_xdr_sc_val(), scval.to_bytes(public)], "deploy_admin", code)
            journal["assets"][code] = {"issuer": issuer.public_key, "holder": holder.public_key,
                                       "sac": sac, "admin": admin, "issuer_created_this_run": True}
            invoke(issuer, sac, "set_admin", [Address(admin).to_xdr_sc_val()], "handover", code)
            invoke(deployer, registry, "register_asset", [Address(sac).to_xdr_sc_val(), Address(source).to_xdr_sc_val()], "register_policy", code)
            for role, signer_address, algo in (("Freeze", admin, "MlDsa65"), ("Mint", issuer.public_key, "Ed25519"), ("Clawback", issuer.public_key, "Ed25519")):
                signer = scval.to_struct({"address": Address(signer_address).to_xdr_sc_val(),
                                          "algo": scval.to_enum(algo, None), "weight": scval.to_uint32(1)})
                quorum = scval.to_struct({"signers": scval.to_vec([signer]), "threshold": scval.to_uint32(1)})
                revision = read(source, registry, "policy_assessment", [Address(sac).to_xdr_sc_val()])["value"]["policy_revision"]
                invoke(deployer, registry, "set_role_quorum_if_revision", [Address(sac).to_xdr_sc_val(), scval.to_enum(role, None), quorum,
                       scval.to_uint64(revision)], "declare_" + role, code)
            assessment = read(source, registry, "policy_assessment", [Address(sac).to_xdr_sc_val()])
            journal["assets"][code]["policy_revision"] = assessment["value"]["policy_revision"]
            journal["assets"][code]["policy_read"] = assessment
            tx = builder(holder).append_change_trust_op(asset).set_timeout(300).build()
            submit(tx, holder, "open_trustline", code)
            save()

        def authorized_tx(code, function="set_authorized", mutation=None, entry=None):
            item = journal["assets"][code]
            values = [Address(item["holder"]).to_xdr_sc_val(), scval.to_bool(True) if function == "set_authorized" else scval.to_int128(10000000)]
            unsigned = builder(deployer).append_invoke_contract_function_op(item["sac"], function, values).set_timeout(300).build()
            if entry is None:
                simulation = simulate(unsigned, "record")
                if simulation.get("error"):
                    raise RuntimeError(f"recording authorization failed: {simulation['error']}")
                auths = simulation["results"][0].get("auth", [])
                if len(auths) != 1:
                    raise RuntimeError("expected exactly one custom-account authorization")
                recorded = xdr.SorobanAuthorizationEntry.from_xdr(auths[0])
                if Address.from_xdr_sc_address(recorded.credentials.address.address).address != item["admin"]:
                    raise RuntimeError("unexpected authorization identity")
                def sign(preimage):
                    signature = helper("sign", "--key", str(key_path), "--payload", authorization_payload_hash(preimage).hex())
                    if len(signature) != 3309:
                        raise RuntimeError("unexpected signature length")
                    if mutation == "corrupted":
                        signature = bytes([signature[0] ^ 1]) + signature[1:]
                    return scval.to_bytes(signature)
                entry = authorize_entry(recorded, sign, rpc("getLatestLedger")["sequence"] + 100,
                                        "wrong-network" if mutation == "wrong_network" else PASSPHRASE)
            tx = builder(deployer).append_invoke_contract_function_op(item["sac"], function, values, auth=[entry]).set_timeout(300).build()
            return tx, copy.deepcopy(entry)

        def rejected(tx, label, code, expected_error):
            result = simulate(tx, "enforce")
            error = result.get("error", "")
            record({"label": label, "asset": code, "kind": "simulation", "auth_mode": "enforce",
                    "expected": "REJECT", "observed": "REJECT" if error else "SUCCESS",
                    "expected_error": expected_error, "envelope_xdr": tx.to_xdr(), "result": result})
            if expected_error not in error:
                raise RuntimeError(f"{label}: expected {expected_error}, got {error or 'success'}")
            print(f"{label} {code}: rejected in simulation", flush=True)

        for code in ("QEXP", "QCTL"):
            item = journal["assets"][code]
            signer = scval.to_struct({"address": Address(item["admin"]).to_xdr_sc_val(),
                      "algo": scval.to_enum("MlDsa65", None), "weight": scval.to_uint32(1)})
            quorum = scval.to_struct({"signers": scval.to_vec([signer]), "threshold": scval.to_uint32(1)})
            conflict = builder(deployer).append_invoke_contract_function_op(registry, "set_role_quorum_if_revision",
                [Address(item["sac"]).to_xdr_sc_val(), scval.to_enum("Freeze", None), quorum, scval.to_uint64(0)]).set_timeout(300).build()
            operation = conflict.transaction.operations[0]
            operation.auth = [xdr.SorobanAuthorizationEntry(
                xdr.SorobanCredentials(xdr.SorobanCredentialsType.SOROBAN_CREDENTIALS_SOURCE_ACCOUNT),
                xdr.SorobanAuthorizedInvocation(xdr.SorobanAuthorizedFunction(
                    xdr.SorobanAuthorizedFunctionType.SOROBAN_AUTHORIZED_FUNCTION_TYPE_CONTRACT_FN,
                    contract_fn=operation.host_function.invoke_contract), []))]
            rejected(conflict, "registry_revision_conflict", code, "Contract, #15")
            tx, consumed = authorized_tx(code)
            submit(tx, deployer, "ml_dsa_set_authorized", code, soroban=True)
            state = account(journal["assets"][code]["holder"])
            trustline = next(b for b in state["balances"] if b.get("asset_code") == code and b.get("asset_issuer") == journal["assets"][code]["issuer"])
            if not trustline["is_authorized"]:
                raise RuntimeError("ML-DSA transaction did not authorize the trustline")
            journal["assets"][code]["authorized_trustline"] = trustline
            rejected(authorized_tx(code, mutation="corrupted")[0], "corrupted_signature", code, "Contract, #3")
            rejected(authorized_tx(code, mutation="wrong_network")[0], "wrong_network_signature", code, "Contract, #3")
            rejected(authorized_tx(code, function="mint")[0], "operator_mint", code, "Contract, #4")
            rejected(authorized_tx(code, entry=consumed)[0], "replayed_entry", code, "Auth")

        issuer = keys["issuer_QEXP"]
        item = journal["assets"]["QEXP"]
        asset = Asset("QEXP", issuer.public_key)
        tx = builder(issuer).append_payment_op(item["holder"], asset, "1").set_timeout(300).build()
        submit(tx, issuer, "classic_mint", "QEXP")
        tx = (builder(issuer).append_set_trust_line_flags_op(item["holder"], asset,
              set_flags=TrustLineFlags.AUTHORIZED_FLAG).set_timeout(300).build())
        submit(tx, issuer, "classic_trustline_flags", "QEXP")
        journal["lock_gate"]["issuer_created_this_run"] = journal["assets"]["QCTL"]["issuer"] in generated
        if not journal["lock_gate"]["environment_enabled"]:
            journal["status"] = "pending_issuer_lock"
            journal["lock_gate"]["reason"] = "QASSET_ALLOW_DISPOSABLE_ISSUER_LOCK=YES was not set; stopped before lock"
        else:
            issuer = keys["issuer_QCTL"]
            state = account(issuer.public_key)
            if not issuer_lock_allowed(os.environ, issuer.public_key,
                                       {keys["issuer_QEXP"].public_key, keys["issuer_QCTL"].public_key}, state):
                raise RuntimeError("issuer-lock gate was withdrawn")
            tx = builder(issuer).append_set_options_op(master_weight=0).set_timeout(300).build()
            submit(tx, issuer, "lock_issuer", "QCTL")
            locked = account(issuer.public_key)
            if any(s["weight"] for s in locked["signers"]):
                raise RuntimeError("issuer still has a signing path after lock")
            journal["lock_gate"]["state"] = "LOCKED"
            item = journal["assets"]["QCTL"]
            tx = builder(issuer).append_payment_op(item["holder"], Asset("QCTL", issuer.public_key), "1").set_timeout(300).build()
            submit(tx, issuer, "classic_mint_after_lock", "QCTL", expected="REJECT")
            tx, _ = authorized_tx("QCTL")
            submit(tx, deployer, "ml_dsa_after_lock", "QCTL", soroban=True)
            journal["status"] = "completed"
        journal["end_ledger"] = rpc("getLatestLedger")["sequence"]
        save()
        print(f"Public deployment record: {args.output} ({journal['status']})", flush=True)
    except Exception as error:
        journal["status"] = "failed"
        journal["failure"] = str(error)
        save()
        raise


if __name__ == "__main__":
    main()
